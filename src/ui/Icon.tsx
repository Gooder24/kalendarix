export function Icon({ name, size }: { name: IconName; size?: number }) {
  if (pixelLook.value) {
    // Whole multiples of the grid, or the squares stop being squares.
    const s = size && size >= 32 ? 32 : 16;
    return (
      <svg class="icon" width={s} height={s} viewBox="0 0 16 16" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">
        <path d={PIXEL[name].join('')} />
      </svg>
    );
  }
  const s = size ?? 18;
  return (
    <svg class="icon" width={s} height={s} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
      <path d={LINE[name]} />
    </svg>
  );
}
